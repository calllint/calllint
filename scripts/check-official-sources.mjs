#!/usr/bin/env node
/**
 * Observes the vendor sources named in `scripts/distribution-sources.json` and records what
 * it saw as an internal artifact.
 *
 * new19 §19: "official source changes" is one of the five weekly checks, and its handling is
 * specified there — "No change: silent. Change: generate internal artifact. Never auto
 * submit. Never auto open external PR."
 *
 * ─────────────────────────────────────────────────────────────────────────────────────────
 * WHY THIS EXITS 0 WHEN A SOURCE IS UNREACHABLE, WHEN `verify-registry-presence.mjs`
 * EXITS 1 FOR THE SAME SYMPTOM
 * ─────────────────────────────────────────────────────────────────────────────────────────
 * That script's comment says "A monitor that cannot observe its subject reports failure, not
 * health," and it is right — about ITS subject. The subjects differ, and the difference
 * decides the exit code:
 *
 *   - Registry presence is a fact about OUR OWN publication. If it cannot be read, our
 *     published claim is unverified, and an unverified claim about ourselves must red.
 *   - A vendor's documentation URL is a fact about THEM. Anthropic moving a page is not a
 *     CallLint defect. A job that reds on it trains maintainers to ignore a red job, which
 *     costs more than the signal is worth — and the failure it would mask is the internal
 *     drift check in the same workflow, which is a real bug every time.
 *
 * So a 404, a timeout, a TLS error and a 500 are all DATA here, written to the artifact and
 * reported as an observation. This script fails only when it cannot do ITS OWN job: an
 * unreadable or empty source manifest, or an unwritable artifact path.
 *
 * The artifact is a JSON snapshot per source: HTTP status, a strong validator when the
 * server offers one (ETag / Last-Modified), and the SHA-256 of the response body. Change is
 * detected by comparing against the previous committed snapshot — the body hash is what
 * makes it work on servers that send neither validator.
 *
 * NOT AN ASSERTION ABOUT CONTENT. A hash change means "this page is not byte-identical to
 * last week," which on a marketing page is usually a rotated banner, not a product change.
 * Deciding whether a change matters is a human's job; the artifact exists so that a human
 * has something to look at. Do not add a heuristic that guesses.
 *
 * READ-ONLY toward the outside world: GET only, no credentials, no form posts, no issue or
 * PR creation. `--offline` skips every fetch and is what CI uses when a run must not touch
 * the network at all.
 */
import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs'
import { createHash } from 'node:crypto'
import path from 'node:path'
import { fileURLToPath } from 'node:url'

const repoRoot = fileURLToPath(new URL('..', import.meta.url))
const MANIFEST = 'scripts/distribution-sources.json'
const ARTIFACT = 'artifacts/distribution-watch/official-sources.json'
const TIMEOUT_MS = 15000

const offline = process.argv.includes('--offline')

/** Fails the run: this checker could not do its own job, which is different from a source being down. */
const die = (message, ...detail) => {
  console.error(`✗ ${message}`)
  for (const line of detail) console.error(`    ${line}`)
  process.exit(1)
}

const manifestAbs = path.join(repoRoot, MANIFEST)
if (!existsSync(manifestAbs)) {
  die(`${MANIFEST} is absent`, 'It is generated by scripts/generate-distribution-surfaces.mjs — run `pnpm gen:distribution`.')
}

let manifest
try {
  manifest = JSON.parse(readFileSync(manifestAbs, 'utf8'))
} catch (error) {
  die(`${MANIFEST} is not parseable JSON`, error.message)
}

// Anti-vacuity. A manifest that silently became empty would make every assertion below
// trivially true and the job would report health having fetched nothing.
const sources = Array.isArray(manifest.sources) ? manifest.sources : []
if (sources.length === 0) {
  die(`${MANIFEST} names zero sources`, 'This checker would observe nothing and still exit 0.')
}

const urls = []
for (const source of sources) {
  for (const url of source.primarySources ?? []) {
    urls.push({ hostId: source.hostId, url, watchFor: source.watchFor ?? null })
  }
}
if (urls.length === 0) {
  die(`${MANIFEST} has sources but zero primarySources URLs`, 'Nothing is observable.')
}

const sha256 = (input) => createHash('sha256').update(input).digest('hex')

/**
 * One GET, with every failure mode mapped to an observation rather than a throw. `redirect`
 * is followed because a vendor moving a doc to a new path is the ordinary case and the final
 * URL is itself worth recording.
 */
const observe = async ({ hostId, url, watchFor }) => {
  const controller = new AbortController()
  const timer = setTimeout(() => controller.abort(), TIMEOUT_MS)
  try {
    const response = await fetch(url, {
      redirect: 'follow',
      signal: controller.signal,
      headers: { 'user-agent': 'calllint-distribution-watch (+https://calllint.com)' },
    })
    const body = await response.text()
    return {
      hostId,
      url,
      watchFor,
      reachable: true,
      status: response.status,
      finalUrl: response.url === url ? null : response.url,
      etag: response.headers.get('etag'),
      lastModified: response.headers.get('last-modified'),
      bodySha256: sha256(body),
      bodyBytes: body.length,
    }
  } catch (error) {
    // Deliberately an observation, not a failure. See the header comment.
    return {
      hostId,
      url,
      watchFor,
      reachable: false,
      status: null,
      finalUrl: null,
      etag: null,
      lastModified: null,
      bodySha256: null,
      bodyBytes: null,
      unreachableReason: error.name === 'AbortError' ? `timeout after ${TIMEOUT_MS}ms` : error.message,
    }
  } finally {
    clearTimeout(timer)
  }
}

const artifactAbs = path.join(repoRoot, ARTIFACT)
const previous = existsSync(artifactAbs) ? JSON.parse(readFileSync(artifactAbs, 'utf8')) : null
const previousByUrl = new Map((previous?.observations ?? []).map((o) => [o.url, o]))

if (offline) {
  console.log(`• --offline: ${urls.length} URL(s) from ${MANIFEST} were NOT fetched.`)
  console.log(`  Manifest shape verified (${sources.length} source(s)); no observation was made or written.`)
  process.exit(0)
}

console.log(`Observing ${urls.length} vendor source(s) named in ${MANIFEST} …`)
const observations = await Promise.all(urls.map(observe))

/**
 * Change classification. `NEW` is separated from `CHANGED` because a URL appearing for the
 * first time has no previous state to differ from — reporting it as a change would be a
 * false positive on every SSOT addition, and this workstream just added three hosts.
 */
const changes = []
for (const now of observations) {
  const before = previousByUrl.get(now.url)
  if (!before) {
    changes.push({ url: now.url, hostId: now.hostId, kind: 'NEW', detail: 'first observation; no baseline' })
    continue
  }
  if (before.status !== now.status) {
    changes.push({ url: now.url, hostId: now.hostId, kind: 'STATUS', detail: `${before.status} → ${now.status}` })
  }
  if (before.reachable !== now.reachable) {
    changes.push({
      url: now.url,
      hostId: now.hostId,
      kind: 'REACHABILITY',
      detail: now.reachable ? 'was unreachable, now reachable' : `now unreachable: ${now.unreachableReason}`,
    })
  }
  if (before.bodySha256 && now.bodySha256 && before.bodySha256 !== now.bodySha256) {
    changes.push({
      url: now.url,
      hostId: now.hostId,
      kind: 'BODY',
      detail: `sha256 ${before.bodySha256.slice(0, 12)} → ${now.bodySha256.slice(0, 12)}`,
    })
  }
  if (now.finalUrl && before.finalUrl !== now.finalUrl) {
    changes.push({ url: now.url, hostId: now.hostId, kind: 'REDIRECT', detail: `now resolves to ${now.finalUrl}` })
  }
}

const gone = [...previousByUrl.keys()].filter((url) => !observations.some((o) => o.url === url))
for (const url of gone) {
  changes.push({ url, hostId: previousByUrl.get(url)?.hostId ?? null, kind: 'DROPPED', detail: 'no longer named in the SSOT' })
}

mkdirSync(path.dirname(artifactAbs), { recursive: true })
writeFileSync(
  artifactAbs,
  `${JSON.stringify(
    {
      $comment:
        'GENERATED by scripts/check-official-sources.mjs. Observation only: an entry here records what a vendor URL returned, ' +
        'not a judgement about CallLint support. A body hash change is usually a rotated banner, not a product change — a human ' +
        'decides whether it matters. This file is the baseline for the next run, so it must be committed for change detection to work.',
      describes: { manifest: MANIFEST, release: manifest.describes?.release ?? null },
      observations: observations.sort((a, b) => a.url.localeCompare(b.url)),
    },
    null,
    2,
  )}\n`,
)

const unreachable = observations.filter((o) => !o.reachable)
const nonOk = observations.filter((o) => o.reachable && (o.status < 200 || o.status >= 300))

console.log('')
console.log(`Observed ${observations.length} URL(s): ${observations.length - unreachable.length} reachable, ${unreachable.length} unreachable`)
for (const o of unreachable) console.log(`    unreachable  ${o.hostId}  ${o.url} — ${o.unreachableReason}`)
for (const o of nonOk) console.log(`    HTTP ${o.status}     ${o.hostId}  ${o.url}`)

if (changes.length === 0) {
  // §19: "No change: silent."
  console.log('')
  console.log(`✓ no change against the previous snapshot. Artifact refreshed at ${ARTIFACT}.`)
  process.exit(0)
}

console.log('')
console.log(`• ${changes.length} change(s) against the previous snapshot:`)
for (const c of changes) console.log(`    [${c.kind}] ${c.hostId ?? '—'}  ${c.url}  ${c.detail}`)
console.log('')
console.log(`  Recorded in ${ARTIFACT}. §19 forbids acting on this automatically: no external PR, no`)
console.log('  issue, no form, no maintainer contact. A human reads the artifact and decides whether the')
console.log('  SSOT needs an edit. Exit 0 — a vendor changing their own page is not a CallLint failure.')
process.exit(0)

#!/usr/bin/env node
/**
 * Observes the vendor sources named in `scripts/distribution-sources.json` and records what
 * it saw as an internal artifact.
 *
 * new19 §19: "official source changes" is one of the five weekly checks, and its handling is
 * specified there — "No change: silent. Change: generate internal artifact. Never auto
 * submit. Never auto open external PR."
 *
 * ─────────────────────────────────────────────────────────────────────────────────────────
 * WHY THIS EXITS 0 WHEN A SOURCE IS UNREACHABLE, WHEN `verify-registry-presence.mjs`
 * EXITS 1 FOR THE SAME SYMPTOM
 * ─────────────────────────────────────────────────────────────────────────────────────────
 * That script's comment says "A monitor that cannot observe its subject reports failure, not
 * health," and it is right — about ITS subject. The subjects differ, and the difference
 * decides the exit code:
 *
 *   - Registry presence is a fact about OUR OWN publication. If it cannot be read, our
 *     published claim is unverified, and an unverified claim about ourselves must red.
 *   - A vendor's documentation URL is a fact about THEM. Anthropic moving a page is not a
 *     CallLint defect. A job that reds on it trains maintainers to ignore a red job, which
 *     costs more than the signal is worth — and the failure it would mask is the internal
 *     drift check in the same workflow, which is a real bug every time.
 *
 * So a 404, a timeout, a TLS error and a 500 are all DATA here, written to the artifact and
 * reported as an observation. This script fails only when it cannot do ITS OWN job: an
 * unreadable or empty source manifest, or an unwritable artifact path.
 *
 * The artifact is a JSON snapshot per source: HTTP status, a strong validator when the
 * server offers one (ETag / Last-Modified), and the SHA-256 of the response body. Change is
 * detected by comparing against the previous committed snapshot — the body hash is what
 * makes it work on servers that send neither validator.
 *
 * NOT AN ASSERTION ABOUT CONTENT. A hash change means "this page is not byte-identical to
 * last week," which on a marketing page is usually a rotated banner, not a product change.
 * Deciding whether a change matters is a human's job; the artifact exists so that a human
 * has something to look at. Do not add a heuristic that guesses.
 *
 * READ-ONLY toward the outside world: GET only, no credentials, no form posts, no issue or
 * PR creation. `--offline` skips every fetch and is what CI uses when a run must not touch
 * the network at all.
 */
import { readFileSync, writeFileSync, existsSync, mkdirSync } from 'node:fs'
import { createHash } from 'node:crypto'
import path from 'node:path'
import { fileURLToPath } from 'node:url'
import { parse as parseYAML } from 'yaml'
import { normalizeBody, UNCOVERED_CHURN } from './lib/normalize-body.mjs'

const repoRoot = fileURLToPath(new URL('..', import.meta.url))
const MANIFEST = 'scripts/distribution-sources.json'
const WATCH_LIST = 'artifacts/distribution/agent-harness-watch-list.yml'
const ARTIFACT = 'artifacts/distribution-watch/official-sources.json'
const TIMEOUT_MS = 15000

const offline = process.argv.includes('--offline')

/** Fails the run: this checker could not do its own job, which is different from a source being down. */
const die = (message, ...detail) => {
  console.error(`✗ ${message}`)
  for (const line of detail) console.error(`    ${line}`)
  process.exit(1)
}

const manifestAbs = path.join(repoRoot, MANIFEST)
if (!existsSync(manifestAbs)) {
  die(`${MANIFEST} is absent`, 'It is generated by scripts/generate-distribution-surfaces.mjs — run `pnpm gen:distribution`.')
}

let manifest
try {
  manifest = JSON.parse(readFileSync(manifestAbs, 'utf8'))
} catch (error) {
  die(`${MANIFEST} is not parseable JSON`, error.message)
}

// Anti-vacuity. A manifest that silently became empty would make every assertion below
// trivially true and the job would report health having fetched nothing.
const sources = Array.isArray(manifest.sources) ? manifest.sources : []
if (sources.length === 0) {
  die(`${MANIFEST} names zero sources`, 'This checker would observe nothing and still exit 0.')
}

/*
 * ─────────────────────────────────────────────────────────────────────────────────────────
 * WHY `candidateFeeds` IS READ HERE, AND WHY IT IS A SEPARATE `kind`
 * ─────────────────────────────────────────────────────────────────────────────────────────
 * Measured 2026-08-22: this loop used to read `manifest.sources` alone, so the candidate
 * feeds were fetched ZERO times. The generator projected them, the schema constrained them,
 * an invariant asserted the one feed's `role` — and no job ever opened the URL. §84's weekly
 * discovery step ("Weekly discovery job → 发现新的 Agent Surface → Generate candidate record
 * → Human approval") therefore had no observation stage at all. That is the repo's dominant
 * fault class in its purest form: a watcher that cannot observe its subject, kept green by an
 * anti-vacuity floor (`sources.length === 0`) whose denominator did not include the thing
 * being missed.
 *
 * `kind` is carried per-URL rather than inferred from `hostId` because the two kinds license
 * different reactions, and the artifact is read by a human who must not have to remember
 * which is which:
 *
 *   HOST_SOURCE     — authority over an EXISTING host's recorded facts. A change here can
 *                     justify editing `supportClass`, `truthfulCommands`, `configEvidence`.
 *   CANDIDATE_FEED  — evidence that a harness CallLint does not track may exist. §86 and
 *                     new18 §35 permit recording candidate evidence and NOTHING else: no
 *                     extractor, no support page, no support claim, no external submission.
 *                     It is never authority over an existing host's support class.
 *
 * Conflating them is the specific way this feature would turn dangerous: a curated
 * third-party list asserting "supports X" would become a support claim about CallLint.
 * The separate `kind`, plus `watchFor` already fixed by the generator, keeps the artifact
 * unable to express that.
 */
const candidateFeeds = Array.isArray(manifest.candidateFeeds) ? manifest.candidateFeeds : []

const urls = []
for (const source of sources) {
  for (const url of source.primarySources ?? []) {
    urls.push({ kind: 'HOST_SOURCE', hostId: source.hostId, url, watchFor: source.watchFor ?? null })
  }
}
if (urls.length === 0) {
  die(`${MANIFEST} has sources but zero primarySources URLs`, 'Nothing is observable.')
}

const hostUrlCount = urls.length
for (const feed of candidateFeeds) {
  for (const url of feed.primarySources ?? []) {
    urls.push({ kind: 'CANDIDATE_FEED', hostId: feed.feedId, url, watchFor: feed.watchFor ?? null })
  }
}

/*
 * ─────────────────────────────────────────────────────────────────────────────────────────
 * THE THIRD KIND: `HARNESS_RELEASE_FEED`, FROM A HAND-MAINTAINED YAML RATHER THAN THE SSOT
 * ─────────────────────────────────────────────────────────────────────────────────────────
 * The two kinds above answer "did a vendor change what they SAY". This one answers "did a
 * harness SHIP" — a different question with a different signal. A release feed moves every
 * few days on the active harnesses (Codex, gemini-cli and qwen-code publish nightlies), so
 * a BODY change here is expected traffic, not news; what is worth a human's attention is a
 * feed going 404 or redirecting, which means a repo moved and an extractor's assumptions
 * may have moved with it. Four of the twelve entries were already wrong when the list was
 * written — `sst/opencode` had moved to `anomalyco/opencode`, `getcursor/cursor` to
 * `cursor/cursor`, `stackblitz-labs/kiro` never existed, and the Qwen URL pointed at the
 * model weights instead of the CLI.
 *
 * WHY A SEPARATE FILE, AND WHY NOT GENERATED. `scripts/distribution-sources.json` is a
 * projection of `apps/web/data/distribution-surfaces.json` and carries the banner "Do not
 * hand-edit"; release feeds are not a published distribution fact and have no place in the
 * SSOT. Keeping them in a committed YAML makes adding a watch target a reviewable commit
 * rather than a config flag, which is what bounds this stage: the job polls exactly the
 * listed URLs and never follows a link out of one. That is the same read-only stance
 * new18 §86 fixes for the two kinds above (§22 was a miscitation, corrected 2026-08-25).
 *
 * The list is OPTIONAL by design. If the file is absent the two SSOT-backed kinds still run
 * — but an unparseable or empty-when-present list fails, because "I could not read my own
 * watch list" is this script's own job failing, not a vendor being down.
 */
const watchListAbs = path.join(repoRoot, WATCH_LIST)
let watches = []
if (existsSync(watchListAbs)) {
  let watchDoc
  try {
    watchDoc = parseYAML(readFileSync(watchListAbs, 'utf8'))
  } catch (error) {
    die(`${WATCH_LIST} is not parseable YAML`, error.message)
  }
  watches = Array.isArray(watchDoc?.watches) ? watchDoc.watches : []
  if (watches.length === 0) {
    die(
      `${WATCH_LIST} exists but declares zero watches`,
      'Release-feed observation would report a silent 0 while the job still exited 0.',
    )
  }
  for (const watch of watches) {
    if (!watch?.url || !watch?.name) {
      die(`${WATCH_LIST} has an entry missing \`name\` or \`url\``, JSON.stringify(watch))
    }
    urls.push({
      kind: 'HARNESS_RELEASE_FEED',
      hostId: watch.name,
      url: watch.url,
      watchFor: 'new harness release; a 404 or redirect means the feed moved',
    })
  }
}

/*
 * Anti-vacuity for the half just added, with its own denominator. `sources.length === 0`
 * above cannot detect this: it stayed green through the entire period in which candidate
 * discovery observed nothing. A feed declared in the SSOT but contributing no URL means the
 * discovery stage is again unable to see its subject, so it fails rather than reporting a
 * silent 0.
 */
const feedUrlCount = urls.filter((u) => u.kind === 'CANDIDATE_FEED').length
if (candidateFeeds.length > 0 && feedUrlCount === 0) {
  die(
    `${MANIFEST} declares ${candidateFeeds.length} candidate feed(s) but zero of them contribute a URL`,
    'Candidate discovery would observe nothing while the job still exited 0.',
  )
}

const releaseFeedUrlCount = urls.filter((u) => u.kind === 'HARNESS_RELEASE_FEED').length

const sha256 = (input) => createHash('sha256').update(input).digest('hex')

/**
 * One GET, with every failure mode mapped to an observation rather than a throw. `redirect`
 * is followed because a vendor moving a doc to a new path is the ordinary case and the final
 * URL is itself worth recording.
 *
 * Network-level connect failures are retried twice with 1.5s/3s backoff, since a vendor page
 * being intermittently reachable is different from being down. HTTP-level errors (404, 500)
 * are data and are NOT retried. The attempt count is recorded so a reader can see the effort.
 */
const observe = async ({ kind, hostId, url, watchFor }) => {
  const backoff = [0, 1500, 3000] // first attempt + 2 retries
  for (let attempt = 0; attempt < backoff.length; attempt++) {
    if (attempt > 0) await new Promise((r) => setTimeout(r, backoff[attempt]))
    const controller = new AbortController()
    const timer = setTimeout(() => controller.abort(), TIMEOUT_MS)
    try {
      const response = await fetch(url, {
        redirect: 'follow',
        signal: controller.signal,
        headers: { 'user-agent': 'calllint-distribution-watch (+https://calllint.com)' },
      })
      const body = await response.text()
      const normalized = normalizeBody(body)
      return {
        kind,
        hostId,
        url,
        watchFor,
        reachable: true,
        status: response.status,
        finalUrl: response.url === url ? null : response.url,
        etag: response.headers.get('etag'),
        lastModified: response.headers.get('last-modified'),
        bodySha256: sha256(body),
        // The raw hash above is NEVER dropped — a reader must always be able to see that the
        // bytes moved. This second hash is what the BODY comparison uses, so a per-request
        // token cannot masquerade as a product change. See scripts/lib/normalize-body.mjs for
        // the measurement that licenses each rule.
        bodyNormalizedSha256: sha256(normalized.text),
        normalizationApplied: normalized.applied,
        bodyBytes: body.length,
        observeAttempts: attempt + 1,
      }
    } catch (error) {
      // A connect-level error may be transient. An HTTP status (404, 500) is data and the
      // catch block never sees it. So we retry here only for network flakes (DNS, TCP, TLS).
      if (attempt === backoff.length - 1) {
        // Final attempt failed — record it as unreachable.
        return {
          kind,
          hostId,
          url,
          watchFor,
          reachable: false,
          status: null,
          finalUrl: null,
          etag: null,
          lastModified: null,
          bodySha256: null,
          bodyNormalizedSha256: null,
          normalizationApplied: [],
          bodyBytes: null,
          unreachableReason: error.name === 'AbortError' ? `timeout after ${TIMEOUT_MS}ms` : error.message,
          observeAttempts: attempt + 1,
        }
      }
      // else: transient failure, will retry after backoff
    } finally {
      clearTimeout(timer)
    }
  }
}

const artifactAbs = path.join(repoRoot, ARTIFACT)
const previous = existsSync(artifactAbs) ? JSON.parse(readFileSync(artifactAbs, 'utf8')) : null
const previousByUrl = new Map((previous?.observations ?? []).map((o) => [o.url, o]))

/*
 * ─────────────────────────────────────────────────────────────────────────────────────────
 * WHY THE BASELINE'S PRESENCE IS REPORTED OUT LOUD
 * ─────────────────────────────────────────────────────────────────────────────────────────
 * Measured 2026-08-22: on CI there had never been a baseline. `distribution-watch.yml`
 * UPLOADS this artifact and nothing ever downloaded it, and the path is untracked — so
 * `previous` was always null, every URL reported `NEW`, and the change detection below had
 * never once executed. The workflow's own comment asserted that uploading "is what makes
 * week-over-week change detection possible." It was not.
 *
 * The failure was invisible because a missing baseline and a quiet week are both spelled
 * "no interesting output": `NEW` on everything reads like a healthy first run, forever. So
 * the state is now printed unconditionally. A run that compared against nothing says so.
 */
if (previous) {
  console.log(`Baseline: ${previousByUrl.size} URL(s) from a previous snapshot at ${ARTIFACT}.`)
} else {
  console.log(`Baseline: ABSENT (${ARTIFACT} not present).`)
  console.log('  Every URL will report NEW and no change can be detected this run. That is correct')
  console.log('  for a first-ever run and a defect on any later one — the workflow restores the')
  console.log("  previous run's artifact before this step.")
}

if (offline) {
  console.log(`• --offline: ${urls.length} URL(s) were NOT fetched.`)
  console.log(
    `  Manifest shape verified (${sources.length} host source(s) → ${hostUrlCount} URL(s), ` +
      `${candidateFeeds.length} candidate feed(s) → ${feedUrlCount} URL(s)); ` +
      `watch list ${watches.length} entr(ies) → ${releaseFeedUrlCount} URL(s); ` +
      'no observation was made or written.',
  )
  process.exit(0)
}

console.log(
  `Observing ${urls.length} source(s) — ${hostUrlCount} host + ${feedUrlCount} candidate-feed ` +
    `from ${MANIFEST}, ${releaseFeedUrlCount} release-feed from ${WATCH_LIST} …`,
)
const observations = await Promise.all(urls.map(observe))

/**
 * Change classification. `NEW` is separated from `CHANGED` because a URL appearing for the
 * first time has no previous state to differ from — reporting it as a change would be a
 * false positive on every SSOT addition, and this workstream just added three hosts.
 *
 * `kind` here is the CHANGE kind (NEW / STATUS / BODY / …); `sourceKind` is the observed
 * URL's kind (HOST_SOURCE / CANDIDATE_FEED). Both are carried because they answer different
 * questions and a human reading the artifact needs both: `kind` says what moved,
 * `sourceKind` says what a maintainer is permitted to do about it. A BODY change on a host
 * source may justify editing that host's recorded facts; the identical BODY change on a
 * candidate feed licenses recording candidate evidence and nothing more.
 */
const changes = []
/** Raw-byte differences that normalization explained away. Recorded, never reported as change. */
const suppressed = []
for (const now of observations) {
  const before = previousByUrl.get(now.url)
  const at = { url: now.url, hostId: now.hostId, sourceKind: now.kind }
  if (!before) {
    changes.push({ ...at, kind: 'NEW', detail: 'first observation; no baseline' })
    continue
  }
  if (before.status !== now.status) {
    changes.push({ ...at, kind: 'STATUS', detail: `${before.status} → ${now.status}` })
  }
  if (before.reachable !== now.reachable) {
    changes.push({
      ...at,
      kind: 'REACHABILITY',
      detail: now.reachable ? 'was unreachable, now reachable' : `now unreachable: ${now.unreachableReason}`,
    })
  }
  if (before.bodySha256 && now.bodySha256 && before.bodySha256 !== now.bodySha256) {
    // The raw bytes moved. Whether that is REPORTABLE is decided on the normalized hash, so
    // a rotated request-id does not read as a product change. Three cases, all explicit:
    if (before.bodyNormalizedSha256 == null) {
      // A baseline written before this field existed (or restored from an old Actions
      // artifact) cannot be compared normalized. Reporting "no change" here would recreate
      // the defect this watcher's own tests document — a missing baseline and a quiet week
      // spelled identically. So it degrades LOUDLY and falls back to the raw comparison.
      changes.push({
        ...at,
        kind: 'BODY',
        detail:
          `sha256 ${before.bodySha256.slice(0, 12)} → ${now.bodySha256.slice(0, 12)} ` +
          `(baseline predates normalization — compared RAW, so this may be per-request noise)`,
      })
    } else if (before.bodyNormalizedSha256 !== now.bodyNormalizedSha256) {
      changes.push({
        ...at,
        kind: 'BODY',
        detail: `sha256 ${before.bodyNormalizedSha256.slice(0, 12)} → ${now.bodyNormalizedSha256.slice(0, 12)} (normalized)`,
      })
    } else {
      // Raw differs, normalized does not: measured per-request churn. Recorded so the
      // suppression is auditable, but NOT a reportable change.
      suppressed.push({
        ...at,
        detail: `raw sha256 moved, normalized identical; stripped: ${now.normalizationApplied.join(', ') || 'none'}`,
      })
    }
  }
  if (now.finalUrl && before.finalUrl !== now.finalUrl) {
    changes.push({ ...at, kind: 'REDIRECT', detail: `now resolves to ${now.finalUrl}` })
  }
}

const gone = [...previousByUrl.keys()].filter((url) => !observations.some((o) => o.url === url))
for (const url of gone) {
  const before = previousByUrl.get(url)
  changes.push({
    url,
    hostId: before?.hostId ?? null,
    sourceKind: before?.kind ?? null,
    kind: 'DROPPED',
    detail: 'no longer named in the SSOT',
  })
}

mkdirSync(path.dirname(artifactAbs), { recursive: true })
writeFileSync(
  artifactAbs,
  `${JSON.stringify(
    {
      $comment:
        'GENERATED by scripts/check-official-sources.mjs. Observation only: an entry here records what a vendor URL returned, ' +
        'not a judgement about CallLint support. A body hash change is usually a rotated banner, not a product change — a human ' +
        'decides whether it matters. This file is the baseline for the next run, so it must be committed for change detection to work.',
      /*
       * `kind: "CANDIDATE_FEED"` entries are the §84 discovery stage's ONLY output. Reading
       * one licenses recording candidate evidence and nothing else — no extractor, no
       * support page, no support claim, no external submission (new18 §35, new19 §86). A
       * candidate that clears human review enters the SSOT as DEFERRED or DISCOVERY_ONLY;
       * NATIVE requires a bootstrapped extractor, which HD-01 enforces independently.
       */
      candidateEvidencePolicy:
        'CANDIDATE_FEED observations are evidence that an untracked harness may exist. They are never authority ' +
        'over an existing host support class, and never a support claim. Human review decides; admission is ' +
        'DEFERRED or DISCOVERY_ONLY only.',
      /*
       * `kind: "HARNESS_RELEASE_FEED"` entries answer "did a harness ship", not "did a vendor
       * change what they say". A BODY change is ordinary traffic on a nightly publisher and
       * licenses nothing on its own; a STATUS or REDIRECT change is the load-bearing signal,
       * because it means the feed moved and an extractor's config-path assumptions may have
       * moved too. Verifying that is a human's job — this file only records what returned.
       */
      releaseFeedPolicy:
        'HARNESS_RELEASE_FEED observations record that a harness release page moved. A BODY change on a nightly ' +
        'publisher is expected and licenses no edit. A STATUS or REDIRECT change means the feed relocated: a human ' +
        'checks whether the harness config path changed, and updates the extractor and the watch list by commit.',
      /*
       * BODY is decided on `bodyNormalizedSha256`, not `bodySha256`. Both are recorded, so a
       * suppression is always auditable: `suppressedBodyChurn` lists every URL whose raw bytes
       * moved while the normalized bytes did not, naming the rules that fired.
       */
      normalizationPolicy:
        'Each stripped token class was measured to differ between two fetches of the same URL 1.5s apart, an ' +
        'interval in which no product change can occur — so removing it is a fact about the transport, not a ' +
        'judgement about content. The raw hash is never dropped. Churn that cannot be normalized without ' +
        'executing JavaScript is declared in uncoveredChurn, not hidden.',
      uncoveredChurn: UNCOVERED_CHURN,
      suppressedBodyChurn: suppressed,
      describes: { manifest: MANIFEST, watchList: WATCH_LIST, release: manifest.describes?.release ?? null },
      counts: {
        hostSourceUrls: hostUrlCount,
        candidateFeedUrls: feedUrlCount,
        candidateFeeds: candidateFeeds.length,
        harnessReleaseFeedUrls: releaseFeedUrlCount,
        harnessWatches: watches.length,
      },
      observations: observations.sort((a, b) => a.url.localeCompare(b.url)),
    },
    null,
    2,
  )}\n`,
)

const unreachable = observations.filter((o) => !o.reachable)
const nonOk = observations.filter((o) => o.reachable && (o.status < 200 || o.status >= 300))

console.log('')
console.log(`Observed ${observations.length} URL(s): ${observations.length - unreachable.length} reachable, ${unreachable.length} unreachable`)
for (const o of unreachable) console.log(`    unreachable  ${o.hostId}  ${o.url} — ${o.unreachableReason}`)
for (const o of nonOk) console.log(`    HTTP ${o.status}     ${o.hostId}  ${o.url}`)

/*
 * The candidate half is reported on its own line even when nothing changed. Suppressing it
 * would make "candidate discovery observed 0 feeds" and "candidate discovery observed 2 feeds
 * with no change" print identically — which is how this stage went unnoticed for its whole
 * existence. The count is cheap; a silent stage is not.
 */
const feedObs = observations.filter((o) => o.kind === 'CANDIDATE_FEED')
const feedReachable = feedObs.filter((o) => o.reachable).length
console.log(
  `    candidate feeds: ${feedObs.length} URL(s) observed, ${feedReachable} reachable ` +
    '— evidence only; §86 permits no support claim, no submission',
)

/*
 * Printed unconditionally for the same reason as the candidate line above: a silent stage and
 * an absent stage read identically, and that is how the candidate half went unobserved for its
 * whole existence. An unreachable release feed is called out by name — that is the signal this
 * kind exists for, and it is the one case here where a human has something to do.
 */
const releaseObs = observations.filter((o) => o.kind === 'HARNESS_RELEASE_FEED')
const releaseReachable = releaseObs.filter((o) => o.reachable && o.status >= 200 && o.status < 300).length
console.log(
  `    harness release feeds: ${releaseObs.length} URL(s) observed, ${releaseReachable} returning 2xx ` +
    `— from ${WATCH_LIST}; polled as listed, never crawled beyond`,
)
if (releaseObs.length === 0) {
  console.log(`      none listed — ${WATCH_LIST} is absent, so no harness ship signal was observed`)
}

/*
 * Printed in BOTH branches below, before the change list and before the silent exit. A run
 * that suppressed 11 churning URLs and a run that fetched 11 byte-identical pages are
 * different facts, and "no change" alone spells them the same way. One line, always.
 */
if (suppressed.length > 0) {
  console.log('')
  console.log(`  ${suppressed.length} raw body change(s) suppressed as measured per-request churn:`)
  for (const s of suppressed) console.log(`    [BODY:noise] ${s.hostId ?? '—'}  ${s.url}  ${s.detail}`)
  console.log(`  Raw hashes are still recorded in ${ARTIFACT} under suppressedBodyChurn.`)
}

if (changes.length === 0) {
  // §19: "No change: silent."
  console.log('')
  console.log(`✓ no change against the previous snapshot. Artifact refreshed at ${ARTIFACT}.`)
  process.exit(0)
}

console.log('')
console.log(`• ${changes.length} change(s) against the previous snapshot:`)
for (const c of changes) {
  const label = {
    HOST_SOURCE: 'host',
    CANDIDATE_FEED: 'candidate',
    HARNESS_RELEASE_FEED: 'release',
  }[c.sourceKind]
  console.log(`    [${c.kind}] (${label || c.sourceKind}) ${c.hostId ?? '—'}  ${c.url}  ${c.detail}`)
}
console.log('')
console.log(`  Recorded in ${ARTIFACT}. §19 forbids acting on this automatically: no external PR, no`)
console.log('  issue, no form, no maintainer contact. A human reads the artifact and decides whether the')
console.log('  SSOT needs an edit. Exit 0 — a vendor changing their own page is not a CallLint failure.')
if (changes.some((c) => c.sourceKind === 'CANDIDATE_FEED')) {
  console.log('')
  console.log('  A candidate-feed entry moved. §84: generate candidate record → human approval → publish.')
  console.log('  Admission is DEFERRED or DISCOVERY_ONLY only; NATIVE needs a bootstrapped extractor (HD-01).')
}
process.exit(0)
